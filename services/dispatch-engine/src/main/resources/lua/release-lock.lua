-- 내가 잡은 락일 때만 푼다.
--
-- 값 확인 없이 DEL 하면 이런 사고가 난다. A 가 락을 잡고 일하다 느려져서 TTL 15초를 넘겼다.
-- 락이 저절로 풀리고 B 가 새로 잡았다. 뒤늦게 끝난 A 가 마무리로 DEL 을 한다.
-- B 가 잡은 락을 A 가 지운 것이다. 그러면 C 가 또 들어와서 B 와 같이 같은 주문을 배차한다.
--
-- 화장실 문에 이름표를 걸고, 나올 때 그게 내 이름표인지 보고 떼는 것과 같다.
--
-- KEYS[1] = 락 키, ARGV[1] = 내 소유자 이름
-- 반환 1 = 내가 풀었다, 0 = 내 락이 아니었다 (이미 뺏겼다는 뜻)
if redis.call('GET', KEYS[1]) == ARGV[1] then
    return redis.call('DEL', KEYS[1])
end
return 0
